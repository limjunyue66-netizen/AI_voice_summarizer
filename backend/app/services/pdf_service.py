class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically calculate total page count and draw running footers.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748b")) # slate-500
        
        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 755, "AI Voice Summarizer — Summary Report")
            self.setStrokeColor(colors.HexColor("#e2e8f0"))
            self.setLineWidth(0.5)
            self.line(54, 747, 558, 747)

        # Footer
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 36, footer_text)
        self.drawString(54, 36, "Generated by AI Voice Summarizer")
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(54, 48, 558, 48)
        self.restoreState()


class PDFService:
    def __init__(self):
        self.font_name = self._setup_fonts()

    def _setup_fonts(self) -> str:
        """
        Attempts to register a Unicode-capable font from Windows Fonts directory.
        Falls back to HeiseiMin-W3 or standard Helvetica.
        """
        windows_font_candidates = [
            r"C:\Windows\Fonts\msyh.ttc",       # Microsoft YaHei
            r"C:\Windows\Fonts\msyh.ttf",
            r"C:\Windows\Fonts\simhei.ttf",     # SimHei
            r"C:\Windows\Fonts\simsun.ttc",     # SimSun
            r"C:\Windows\Fonts\arialuni.ttf",   # Arial Unicode MS
            r"C:\Windows\Fonts\seguiemj.ttf",
        ]

        for font_path in windows_font_candidates:
            if os.path.exists(font_path):
                try:
                    # For TTC (TrueType Collection), specify subfontIndex=0
                    subfont_idx = 0 if font_path.lower().endswith(".ttc") else None
                    if subfont_idx is not None:
                        pdfmetrics.registerFont(TTFont("CustomUnicodeFont", font_path, subfontIndex=subfont_idx))
                    else:
                        pdfmetrics.registerFont(TTFont("CustomUnicodeFont", font_path))
                    return "CustomUnicodeFont"
                except Exception:
                    continue

        # Try registering Asian CID font available in reportlab
        try:
            pdfmetrics.registerFont(UnicodeCIDFont("STSong-Light"))
            return "STSong-Light"
        except Exception:
            pass

        return "Helvetica"

    def generate_summary_pdf(
        self,
        filename: str,
        detected_language: str,
        summary_language: str,
        summary_data: dict,
        original_transcript: str = ""
    ) -> Path:
        """
        Compiles the AI summary and metadata into a clean, modern PDF report.
        """
        pdf_path = generate_temp_path(f"summary_{filename}", custom_ext="pdf")

        doc = SimpleDocTemplate(
            str(pdf_path),
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        font = self.font_name
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName=font,
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#0284c7"), # Sky-600
            spaceAfter=6,
            wordWrap="CJK"
        )

        subtitle_style = ParagraphStyle(
            "DocSubtitle",
            parent=styles["Normal"],
            fontName=font,
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#64748b"),
            spaceAfter=15,
            wordWrap="CJK"
        )

        h1_style = ParagraphStyle(
            "SectionH1",
            parent=styles["Normal"],
            fontName=font,
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#0f172a"),
            spaceBefore=12,
            spaceAfter=6,
            wordWrap="CJK"
        )

        h2_style = ParagraphStyle(
            "TopicH2",
            parent=styles["Normal"],
            fontName=font,
            fontSize=11,
            leading=15,
            textColor=colors.HexColor("#0369a1"),
            spaceBefore=6,
            spaceAfter=3,
            wordWrap="CJK"
        )

        body_style = ParagraphStyle(
            "Body",
            parent=styles["Normal"],
            fontName=font,
            fontSize=9.5,
            leading=14,
            textColor=colors.HexColor("#334155"),
            spaceAfter=6,
            wordWrap="CJK"
        )

        bullet_style = ParagraphStyle(
            "Bullet",
            parent=styles["Normal"],
            fontName=font,
            fontSize=9.5,
            leading=14,
            textColor=colors.HexColor("#334155"),
            leftIndent=14,
            spaceAfter=4,
            wordWrap="CJK"
        )

        meta_label_style = ParagraphStyle(
            "MetaLabel",
            parent=styles["Normal"],
            fontName=font,
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#475569"),
            wordWrap="CJK"
        )

        meta_val_style = ParagraphStyle(
            "MetaVal",
            parent=styles["Normal"],
            fontName=font,
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#0f172a"),
            wordWrap="CJK"
        )

        story = []

        # 1. Header Banner
        story.append(Paragraph("AI Voice Summarizer", title_style))
        story.append(Paragraph("Intelligent Speech Transcription & Audio Analysis Report", subtitle_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#e2e8f0"), spaceAfter=14))

        # 2. Metadata Box
        generated_date = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        metadata_data = [
            [
                Paragraph("<b>Source File:</b>", meta_label_style),
                Paragraph(filename, meta_val_style),
                Paragraph("<b>Generated On:</b>", meta_label_style),
                Paragraph(generated_date, meta_val_style),
            ],
            [
                Paragraph("<b>Detected Spoken:</b>", meta_label_style),
                Paragraph(detected_language, meta_val_style),
                Paragraph("<b>Summary Language:</b>", meta_label_style),
                Paragraph(summary_language.capitalize(), meta_val_style),
            ],
        ]

        meta_table = Table(metadata_data, colWidths=[100, 160, 95, 149])
        meta_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#f1f5f9")),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 14))

        # 3. Overall Summary
        overall = summary_data.get("overall_summary", "")
        if overall:
            story.append(Paragraph("1. Overall Summary", h1_style))
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#bae6fd"), spaceAfter=6))
            story.append(Paragraph(overall.replace("\n", "<br/>"), body_style))
            story.append(Spacer(1, 10))

        # 4. Key Points
        key_points = summary_data.get("key_points", [])
        if key_points:
            story.append(Paragraph("2. Key Points", h1_style))
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#bae6fd"), spaceAfter=6))
            for item in key_points:
                story.append(Paragraph(f"• {item}", bullet_style))
            story.append(Spacer(1, 10))

        # 5. Important Details
        details = summary_data.get("important_details", [])
        if details:
            story.append(Paragraph("3. Important Details", h1_style))
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#bae6fd"), spaceAfter=6))
            for item in details:
                story.append(Paragraph(f"• {item}", bullet_style))
            story.append(Spacer(1, 10))

        # 6. Main Topics
        topics = summary_data.get("main_topics", [])
        if topics:
            story.append(Paragraph("4. Main Topics", h1_style))
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#bae6fd"), spaceAfter=6))
            for topic_obj in topics:
                if isinstance(topic_obj, dict):
                    t_title = topic_obj.get("topic", "Topic")
                    t_desc = topic_obj.get("description", "")
                    story.append(Paragraph(f"<b>{t_title}</b>", h2_style))
                    if t_desc:
                        story.append(Paragraph(t_desc, body_style))
                else:
                    story.append(Paragraph(f"• {str(topic_obj)}", bullet_style))
            story.append(Spacer(1, 10))

        # 7. Conclusions
        conclusions = summary_data.get("conclusions", [])
        if conclusions:
            story.append(Paragraph("5. Conclusions", h1_style))
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#bae6fd"), spaceAfter=6))
            for item in conclusions:
                story.append(Paragraph(f"• {item}", bullet_style))
            story.append(Spacer(1, 10))

        # Build document with NumberedCanvas
        doc.build(story, canvasmaker=NumberedCanvas)
        return pdf_path

pdf_service = PDFService()

